export function normalizeLocale(value) {
  const normalized = String(value || '').trim().toLowerCase()
  if (normalized === 'zh' || normalized.startsWith('zh-')) return 'zh-CN'
  if (normalized === 'en' || normalized.startsWith('en-')) return 'en'
  return null
}

export function preferredLocale({ stored = null, languages = [] } = {}) {
  const storedLocale = normalizeLocale(stored)
  if (storedLocale) return storedLocale
  for (const language of languages || []) {
    const locale = normalizeLocale(language)
    if (locale) return locale
  }
  return DEFAULT_LOCALE
}

export function t(locale, key, variables = {}) {
  const active = normalizeLocale(locale) || DEFAULT_LOCALE
  const template = messages[active]?.[key] ?? messages[DEFAULT_LOCALE]?.[key] ?? key
  return String(template).replace(/\{([A-Za-z0-9_]+)\}/g, (match, name) => (
    Object.hasOwn(variables, name) ? String(variables[name]) : match
  ))
}

export function formatNumber(locale, value) {
  return new Intl.NumberFormat(normalizeLocale(locale) || DEFAULT_LOCALE).format(Number(value || 0))
}

export function formatDateTime(locale, value) {
  if (!value) return t(locale, 'common.notRecorded')
  const parsed = new Date(value)
  if (Number.isNaN(parsed.valueOf())) return String(value)
  return new Intl.DateTimeFormat(normalizeLocale(locale) || DEFAULT_LOCALE, {
    dateStyle: 'medium',
    timeStyle: 'short',
  }).format(parsed)
}

export function formatCount(locale, value, unit) {
  const active = normalizeLocale(locale) || DEFAULT_LOCALE
  const count = Number(value || 0)
  const forms = units[active]?.[unit] || units[DEFAULT_LOCALE]?.[unit] || [unit, unit]
  return `${formatNumber(active, count)} ${count === 1 ? forms[0] : forms[1]}`
}

export function statusLabel(locale, value) {
  const normalized = String(value || 'record').trim().toLowerCase().replaceAll('-', '_')
  const key = `status.${normalized}`
  const translated = t(locale, key)
  return translated === key ? (String(value || '').trim() || t(locale, 'common.record')) : translated
}

export function translationKeySets() {
  return Object.fromEntries(Object.entries(messages).map(([locale, entries]) => [
    locale,
    Object.keys(entries).sort(),
  ]))
}
